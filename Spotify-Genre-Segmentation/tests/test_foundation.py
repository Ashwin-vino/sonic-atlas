"""
SONIC ATLAS — Unit & Foundation Tests (Phase 1)
Tests configuration, data loader, schema integrity, and preprocessing functions.
"""

import sys
import unittest
from pathlib import Path

# Ensure project root is in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd

from src.config import (
    AUDIO_FEATURES,
    COLOR_PALETTE,
    DATASET_FILENAME,
    DATASET_SCHEMA,
    PROJECT_ROOT,
    RAW_DATA_PATH,
)
from src.data_loader import (
    get_dataset_dimensions,
    get_dataset_summary,
    get_missing_values,
    load_dataset,
    resolve_dataset_path,
)
from src.preprocessing import (
    check_data_types,
    inspect_duplicates,
    inspect_missing_values,
    validate_columns,
)


class TestSonicAtlasFoundation(unittest.TestCase):
    """Test suite for Phase 1 foundational architecture."""

    def test_config_paths_and_tokens(self):
        """Validates that project directories and design tokens are properly defined."""
        self.assertTrue(PROJECT_ROOT.exists(), "PROJECT_ROOT directory must exist.")
        self.assertIn("main_background", COLOR_PALETTE)
        self.assertEqual(COLOR_PALETTE["main_background"], "#090D0B")
        self.assertEqual(COLOR_PALETTE["primary_green"], "#55D99A")
        self.assertEqual(len(AUDIO_FEATURES), 12)
        self.assertEqual(len(DATASET_SCHEMA), 23)

    def test_dataset_resolution(self):
        """Verifies that resolve_dataset_path locates the Spotify songs CSV."""
        path = resolve_dataset_path()
        self.assertTrue(path.is_file(), f"Dataset file must exist at {path}")
        self.assertEqual(path.name, DATASET_FILENAME)

    def test_dataset_loading_and_dimensions(self):
        """Verifies that the dataset loads properly and matches known Spotify dimensions."""
        df = load_dataset()
        rows, cols = get_dataset_dimensions(df)
        self.assertEqual(rows, 32833, f"Expected 32,833 rows, got {rows}")
        self.assertEqual(cols, 23, f"Expected 23 columns, got {cols}")

    def test_schema_fidelity(self):
        """Verifies that all 23 expected schema columns are present in the dataset."""
        df = load_dataset()
        audit = validate_columns(df)
        self.assertTrue(audit["is_valid"], f"Missing columns: {audit['missing_columns']}")
        self.assertEqual(len(audit["missing_columns"]), 0)

    def test_audio_feature_types(self):
        """Verifies that all continuous audio features have numeric dtypes."""
        df = load_dataset()
        type_audit = check_data_types(df)
        self.assertTrue(
            type_audit["is_audio_types_valid"],
            f"Non-numeric audio features found: {type_audit['non_numeric_audio_features']}",
        )

    def test_missing_values_detection(self):
        """Verifies that missing values are accurately detected (exactly 5 metadata rows with NA)."""
        df = load_dataset()
        missing_df = inspect_missing_values(df)
        cols_with_missing = missing_df[missing_df["missing_count"] > 0]
        missing_col_names = set(cols_with_missing["column"])
        expected_missing = {"track_name", "track_artist", "track_album_name"}
        self.assertEqual(missing_col_names, expected_missing)
        for _, row in cols_with_missing.iterrows():
            self.assertEqual(row["missing_count"], 5)

    def test_dataset_summary_metrics(self):
        """Verifies high-level metrics generated by data_loader summary."""
        df = load_dataset()
        summary = get_dataset_summary(df)
        self.assertEqual(summary["total_rows"], 32833)
        self.assertEqual(summary["exact_duplicates"], 0)
        self.assertEqual(summary["unique_genres"], 6)
        self.assertEqual(summary["unique_subgenres"], 24)
        self.assertEqual(summary["unique_tracks"], 28356)


if __name__ == "__main__":
    unittest.main()
